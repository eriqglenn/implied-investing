"""Income Lab automated refresh.

State lives in one JSON file (seed: site/lab/state.json; on the host: $II_LAB_DIR/state.json on the persistent disk).
Each run rebuilds the three files the Income Lab page loads, in $II_LAB_DIR (served instead of site/web when present):
  builder_funds.js    issuers, funds, distribution rates, fees
  builder_details.js  strategy + top-10 holdings per fund
  builder_prices.js   daily closes + distributions (performance chart)
and writes lab_report.json (what updated, what failed, what needs a human).

  prices  daily   Yahoo Finance daily closes + distributions for every fund and the SPY / QQQ benchmarks
  weekly  weekly  issuer holdings (top 10) and, where the issuer publishes it in a readable feed, the distribution rate

Run locally:   py -3 -B site/lab/refresh.py prices|weekly|all [--out DIR]
By hand:       py -3 -B site/lab/refresh.py set-rate MSTY 75.81 2026-10-06 "YieldMax press release Oct 7"
Never trades, never touches member data. A fund whose issuer can't be read keeps its last good values and is reported.
"""
import argparse, datetime as dt, importlib, json, os, sys, time, traceback
from pathlib import Path

HERE = Path(__file__).resolve().parent
SITE = HERE.parent
SEED = HERE / 'state.json'
BENCH = ['SPY', 'QQQ']
STALE_DAYS = 45
UA = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'}


def out_dir():
    return Path(os.environ.get('II_LAB_DIR') or (SITE / 'web'))


def state_path():
    d = os.environ.get('II_LAB_DIR')
    return Path(d) / 'state.json' if d else SEED


def load_state():
    """The repo seed defines the lineup (issuers, funds, names, strategies); the disk copy holds the latest refreshed values.
    Funds added to the seed appear on the next run, funds removed from it disappear, refreshed data is kept."""
    seed = json.loads(SEED.read_text(encoding='utf8')); p = state_path()
    if p == SEED or not p.exists():
        return seed
    disk = json.loads(p.read_text(encoding='utf8'))
    have = {f['t']: f for i in disk.get('issuers', []) for f in i['funds']}
    LIVE = ('rate', 'rate_asof', 'rate_source', 'rate_checked', 'holdings', 'checked')
    for is_ in seed['issuers']:
        for f in is_['funds']:
            old = have.get(f['t'])
            if old and (old.get('checked') or '') >= (f.get('checked') or ''):
                f.update({k: old[k] for k in LIVE if k in old})
    seed['built'] = max(seed.get('built') or '', disk.get('built') or '')
    return seed


def save_state(st):
    p = state_path(); p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix('.tmp'); tmp.write_text(json.dumps(st, indent=1, ensure_ascii=False), encoding='utf8'); tmp.replace(p)


def write_js(name, var, payload, gen='site/lab/refresh.py'):
    d = out_dir(); d.mkdir(parents=True, exist_ok=True)
    tmp = d / (name + '.tmp')
    tmp.write_text(f'/* generated by {gen}; do not edit by hand */\nwindow.{var}=' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n',
                   encoding='utf8')
    tmp.replace(d / name)


def funds(st):
    for is_ in st['issuers']:
        for f in is_['funds']:
            yield is_, f


# ----------------------------------------------------------------------------------------------- outputs
def write_outputs(st):
    write_js('builder_funds.js', 'II_FUNDS', dict(
        as_of=st.get('built'), note='Distribution rates as published by each issuer, with the issuer as-of date.',
        issuers=[dict(name=i['name'], url=i['url'], hold=i.get('rate_policy') == 'hold', funds=[dict(t=f['t'], name=f['name'], rate=f['rate'], asof=f['rate_asof'], freq=f['freq'],
                                                               er=f['er'], url=f['url'], official_name=f['official_name']) for f in i['funds']])
                 for i in st['issuers']]))
    write_js('builder_details.js', 'II_DETAILS', dict(built=st.get('built'), f={
        f['t']: dict(n=f['official_name'], s=f['strategy'], h=dict(a=f['holdings'].get('as_of'), u=f['holdings'].get('source_url'),
                                                                    n=f['holdings'].get('total'), t=f['holdings'].get('top') or []))
        for _, f in funds(st)}))


# ----------------------------------------------------------------------------------------------- http
class Http:
    """requests session with a browser UA, timeouts and two retries."""
    def __init__(self):
        import requests
        self.s = requests.Session(); self.s.headers.update(UA)

    def get(self, url, **kw):
        kw.setdefault('timeout', 45); err = None
        for attempt in range(3):
            try:
                r = self.s.get(url, **kw)
                if r.status_code == 200:
                    return r
                err = f'HTTP {r.status_code}'
            except Exception as e:                       # network hiccup: retry
                err = f'{type(e).__name__}: {e}'
            time.sleep(1.5 * (attempt + 1))
        raise RuntimeError(f'GET {url} failed: {err}')

    def post(self, url, **kw):
        kw.setdefault('timeout', 45)
        r = self.s.post(url, **kw)
        if r.status_code != 200:
            raise RuntimeError(f'POST {url} failed: HTTP {r.status_code}')
        return r


# ----------------------------------------------------------------------------------------------- weekly: holdings + rates
def _fetcher(key):
    sys.path.insert(0, str(HERE.parent)) if str(HERE.parent) not in sys.path else None
    return importlib.import_module(f'lab.fetchers.{key}')


def _check_holdings(h):
    top = h.get('top') or []
    if not top:
        return 'no holdings returned'
    if not all(isinstance(x, (list, tuple)) and len(x) == 4 and isinstance(x[2], (int, float)) for x in top):
        return 'holdings rows malformed'
    if max(abs(x[2]) for x in top) > 250:
        return 'implausible weight'
    return None


def _check_rate(r):
    v = r.get('value_pct')
    if not isinstance(v, (int, float)) or not (0 <= v <= 400):
        return f'implausible rate {v!r}'
    return None


def refresh_weekly(st, only=None, log=print):
    rep = dict(kind='weekly', started=dt.datetime.now().isoformat(timespec='seconds'), holdings_ok=[], holdings_failed={}, rates_ok=[],
               rates_manual=[], rates_held=[], rates_failed={}, stale=[])
    http = Http(); today = dt.date.today()
    for is_, f in funds(st):
        if only and is_['key'] not in only and f['t'] not in only:
            continue
        try:
            mod = _fetcher(is_['key'])
        except Exception as e:
            rep['holdings_failed'][f['t']] = f'no reader for {is_["key"]}: {e}'; continue
        # holdings
        try:
            h = mod.holdings(f, http); bad = _check_holdings(h)
            if bad:
                raise RuntimeError(bad)
            f['holdings'] = dict(as_of=h.get('as_of'), source_url=h.get('source_url'), total=h.get('total'), top=[list(x) for x in h['top'][:10]])
            rep['holdings_ok'].append(f['t'])
        except Exception as e:
            rep['holdings_failed'][f['t']] = str(e)[:300]
        # rate (only where the issuer publishes it in a readable form)
        rate_read = False
        if is_.get('rate_policy') == 'hold':                # issuer doesn't publish rates; keep the recorded values, no flags
            rep['rates_held'].append(f['t']); f['checked'] = today.isoformat(); time.sleep(0.3); continue
        if getattr(mod, 'RATES', False):
            try:
                r = mod.rate(f, http)
                if r is None:
                    rep['rates_manual'].append(f['t'])
                else:
                    bad = _check_rate(r)
                    if bad:
                        raise RuntimeError(bad)
                    f['rate'] = round(float(r['value_pct']), 2); f['rate_asof'] = r.get('as_of'); f['rate_source'] = r.get('source_url')
                    f['rate_checked'] = today.isoformat(); rate_read = True
                    rep['rates_ok'].append(f['t'])
            except Exception as e:
                rep['rates_failed'][f['t']] = str(e)[:300]
        else:
            rep['rates_manual'].append(f['t'])
        f['checked'] = today.isoformat()
        a = f.get('rate_asof') or f.get('rate_checked')       # undated issuer rates count from the day we last read them
        if not rate_read and (not a or (today - dt.date.fromisoformat(a[:10])).days > STALE_DAYS):
            rep['stale'].append(dict(t=f['t'], issuer=is_['name'], rate_asof=a))
        time.sleep(0.3)
    st['built'] = today.isoformat()
    rep['finished'] = dt.datetime.now().isoformat(timespec='seconds')
    log(f"weekly: holdings {len(rep['holdings_ok'])} ok / {len(rep['holdings_failed'])} failed; rates {len(rep['rates_ok'])} ok / "
        f"{len(rep['rates_failed'])} failed / {len(rep['rates_manual'])} manual / {len(rep['rates_held'])} held; stale {len(rep['stale'])}")
    return rep


# ----------------------------------------------------------------------------------------------- daily: prices
def refresh_prices(st, log=print):
    """Daily closes + distributions from Yahoo Finance for every fund and the benchmarks -> builder_prices.js."""
    import pandas as pd
    http = Http(); tickers = [f['t'] for _, f in funds(st)] + BENCH
    end = int(time.time()) + 86400
    url = 'https://query1.finance.yahoo.com/v8/finance/chart/{t}?period1=946684800&period2={e}&interval=1d&events=div%2Csplit&includeAdjustedClose=true'
    closes, divs, failed = {}, {}, {}
    day = lambda ts, off: dt.datetime.fromtimestamp(ts + off, dt.timezone.utc).date()
    for t in tickers:
        try:
            r = http.get(url.format(t=t, e=end)).json()['chart']['result'][0]
            if r['meta'].get('dataGranularity') != '1d':            # range=max quietly switches to weekly bars; we never accept that
                raise RuntimeError(f"granularity {r['meta'].get('dataGranularity')}")
            off = r['meta'].get('gmtoffset', 0)
            s = pd.Series(r['indicators']['quote'][0]['close'], index=[day(x, off) for x in r['timestamp']], dtype=float).dropna()
            closes[t] = s[~s.index.duplicated(keep='last')]
            divs[t] = sorted((day(int(k), off), float(v['amount'])) for k, v in ((r.get('events') or {}).get('dividends') or {}).items())
        except Exception as e:
            failed[t] = str(e)[:200]
        time.sleep(0.25)
    if any(b not in closes for b in BENCH) or len(closes) < 0.9 * len(tickers):
        raise RuntimeError(f'too many price failures ({len(failed)}): keeping the previous file')
    first_fund = min(closes[t].index.min() for t in closes if t not in BENCH)
    for b in BENCH:
        closes[b] = closes[b][closes[b].index >= first_fund]; divs[b] = [x for x in divs[b] if x[0] >= first_fund]
    cal = sorted(set().union(*[set(s.index) for s in closes.values()])); pos = {d: i for i, d in enumerate(cal)}
    F = {}
    for t, s in closes.items():
        full = s.reindex(cal).ffill(); i0 = pos[s.index.min()]
        dv = []
        for d, amt in divs[t]:
            k = next((i for i in range(pos.get(d, 0), len(cal)) if cal[i] >= d), None)
            if k is not None and k > i0:
                dv.append([k, round(amt, 5)])
        F[t] = dict(s=i0, c=[round(v, 2 if v >= 10 else 4) for v in full.iloc[i0:]], d=dv)
    write_js('builder_prices.js', 'II_PRICES', dict(source='Yahoo Finance daily closes and distribution history', fetched=str(dt.date.today()),
                                                    dates=[str(d) for d in cal], f=F))
    rep = dict(kind='prices', finished=dt.datetime.now().isoformat(timespec='seconds'), tickers=len(F), failed=failed, last_close=str(cal[-1]))
    log(f"prices: {len(F)} tickers through {cal[-1]}; {len(failed)} failed")
    return rep


# ----------------------------------------------------------------------------------------------- reports
def save_report(rep):
    p = out_dir() / 'lab_report.json'
    old = json.loads(p.read_text(encoding='utf8')) if p.exists() else {}
    old[rep['kind']] = rep; old['updated'] = dt.datetime.now().isoformat(timespec='seconds')
    p.write_text(json.dumps(old, indent=1), encoding='utf8')


def set_rate(ticker, value, as_of, source):
    """Record a rate read by hand from an issuer document (e.g. a YieldMax press release), then rebuild the page data."""
    st = load_state(); hit = [f for _, f in funds(st) if f['t'] == ticker.upper()]
    if not hit:
        raise SystemExit(f'{ticker} is not an Income Lab fund')
    v = float(value); dt.date.fromisoformat(as_of)
    if not 0 <= v <= 400:
        raise SystemExit(f'implausible rate {v}')
    f = hit[0]; old = (f['rate'], f['rate_asof'])
    f.update(rate=round(v, 2), rate_asof=as_of, rate_source=f'manual: {source}', rate_checked=dt.date.today().isoformat())
    save_state(st); write_outputs(st)
    print(f'{f["t"]}: {old[0]}% ({old[1]}) -> {f["rate"]}% ({as_of}); saved to {state_path()}')


def run(kind, only=None, log=print):
    st = load_state(); reps = []
    if kind in ('weekly', 'all'):
        reps.append(refresh_weekly(st, only, log)); save_state(st); write_outputs(st)
    if kind in ('prices', 'all'):
        try:
            reps.append(refresh_prices(st, log))
        except Exception as e:
            reps.append(dict(kind='prices', error=str(e), finished=dt.datetime.now().isoformat(timespec='seconds'))); log('prices failed:', e)
    for r in reps:
        save_report(r)
    return reps


if __name__ == '__main__':
    a = argparse.ArgumentParser(); a.add_argument('kind', choices=['prices', 'weekly', 'all', 'outputs', 'set-rate']); a.add_argument('args', nargs='*')
    a.add_argument('--out', help='output folder (default: $II_LAB_DIR or site/web)'); a.add_argument('--only', nargs='*', help='issuer keys or tickers')
    v = a.parse_args()
    if v.out:
        os.environ['II_LAB_DIR'] = v.out
    sys.path.insert(0, str(SITE))
    if v.kind == 'set-rate':
        if len(v.args) != 4:
            raise SystemExit('usage: refresh.py set-rate TICKER RATE_PCT YYYY-MM-DD "source"')
        set_rate(*v.args)
    elif v.kind == 'outputs':
        write_outputs(load_state()); print('outputs written to', out_dir())
    else:
        try:
            run(v.kind, v.only)
        except Exception:
            traceback.print_exc(); sys.exit(1)
